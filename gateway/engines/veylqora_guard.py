"""Veylqora Evidence-Anchored Memory Guard for Musegix Gateway.

Invariants:
1. SQLite WAL Persistence: Tracks SHA-256 fingerprints per file and AST symbol in a
   local SQLite database in Write-Ahead Logging (WAL) mode.
2. Per-Session Isolation: State is strictly partitioned by session_id / chat_id to
   prevent cross-chat contamination.
3. Staleness Detection: Only flags SUSPECTED_STALE when a function, class, or file
   that was cited or present in prior conversation turns has mutated its fingerprint.
"""

from __future__ import annotations

import ast
from dataclasses import dataclass, field
import hashlib
import os
import re
import sqlite3
import time
from typing import Any, Dict, List, Optional, Set, Tuple

# Tree-sitter for TS/TSX/JS AST symbol extraction
_TREE_SITTER_AVAILABLE = False
_TS_PARSER = None
_TSX_PARSER = None
_JS_PARSER = None

try:
    import tree_sitter
    import tree_sitter_typescript
    import tree_sitter_javascript

    _TS_LANG = tree_sitter.Language(tree_sitter_typescript.language_typescript())
    _TSX_LANG = tree_sitter.Language(tree_sitter_typescript.language_tsx())
    _JS_LANG = tree_sitter.Language(tree_sitter_javascript.language())

    _TS_PARSER = tree_sitter.Parser(_TS_LANG)
    _TSX_PARSER = tree_sitter.Parser(_TSX_LANG)
    _JS_PARSER = tree_sitter.Parser(_JS_LANG)
    _TREE_SITTER_AVAILABLE = True
except Exception:
    _TREE_SITTER_AVAILABLE = False


@dataclass
class SymbolFingerprint:
    file_path: str
    symbol_name: str
    symbol_type: str  # "file", "function", "class", "method", "interface", "variable"
    sha256_hash: str
    code_snippet: str = ""


@dataclass
class MutatedSymbol:
    file_path: str
    symbol_name: str
    symbol_type: str
    old_hash: str
    new_hash: str

    def to_dict(self) -> Dict[str, Any]:
        return {
            "file_path": self.file_path,
            "symbol_name": self.symbol_name,
            "symbol_type": self.symbol_type,
            "old_hash": self.old_hash,
            "new_hash": self.new_hash,
        }


@dataclass
class GuardReport:
    """Report generated by VeylqoraGuard after inspecting workspace files."""
    status: str  # "ACTIVE" or "SUSPECTED_STALE"
    stale_count: int
    mutated_symbols: List[MutatedSymbol] = field(default_factory=list)
    total_symbols_tracked: int = 0
    turn_index: int = 0
    session_id: str = ""
    elapsed_ms: float = 0.0

    def to_dict(self) -> Dict[str, Any]:
        return {
            "status": self.status,
            "stale_count": self.stale_count,
            "mutated_symbols": [m.to_dict() for m in self.mutated_symbols],
            "total_symbols_tracked": self.total_symbols_tracked,
            "turn_index": self.turn_index,
            "session_id": self.session_id,
            "elapsed_ms": self.elapsed_ms,
        }

    def banner_text(self) -> str:
        if self.status == "SUSPECTED_STALE":
            return f"> 🧠 **Veylqora Memory**: `SUSPECTED_STALE` ({self.stale_count} mutated symbols detected)\n"
        return "> 🧠 **Veylqora Memory**: `ACTIVE` (0 stale memories detected)\n"


def sha256_text(text: str) -> str:
    """Compute standard SHA-256 hex digest of a UTF-8 string."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def extract_ts_js_symbols(file_path: str, code: str) -> List[SymbolFingerprint]:
    """Extract AST symbols and fingerprints from TypeScript / TSX / JavaScript."""
    symbols: List[SymbolFingerprint] = []

    # 1. Whole-file root fingerprint
    symbols.append(SymbolFingerprint(
        file_path=file_path,
        symbol_name="$file",
        symbol_type="file",
        sha256_hash=sha256_text(code),
    ))

    if not _TREE_SITTER_AVAILABLE or not code.strip():
        return symbols

    ext = os.path.splitext(file_path)[1].lower()
    if ext == ".tsx":
        parser = _TSX_PARSER
    elif ext in (".ts", ".mts", ".cts"):
        parser = _TS_PARSER
    else:
        parser = _JS_PARSER or _TSX_PARSER

    try:
        tree = parser.parse(code.encode("utf-8"))
    except Exception:
        return symbols

    def node_text(n: Any) -> str:
        return n.text.decode("utf-8", errors="replace")

    for child in tree.root_node.children:
        node = child
        if node.type == "export_statement":
            for sub in node.children:
                if sub.type in ("function_declaration", "class_declaration", "interface_declaration", "lexical_declaration", "type_alias_declaration"):
                    node = sub
                    break

        ntype = node.type
        if ntype == "function_declaration":
            name_node = node.child_by_field_name("name")
            if name_node:
                sname = node_text(name_node)
                symbols.append(SymbolFingerprint(
                    file_path=file_path,
                    symbol_name=sname,
                    symbol_type="function",
                    sha256_hash=sha256_text(node_text(node)),
                ))
        elif ntype == "interface_declaration":
            name_node = node.child_by_field_name("name")
            if name_node:
                sname = node_text(name_node)
                symbols.append(SymbolFingerprint(
                    file_path=file_path,
                    symbol_name=sname,
                    symbol_type="interface",
                    sha256_hash=sha256_text(node_text(node)),
                ))
        elif ntype == "class_declaration":
            cname_node = node.child_by_field_name("name")
            cname = node_text(cname_node) if cname_node else "AnonymousClass"
            symbols.append(SymbolFingerprint(
                file_path=file_path,
                symbol_name=cname,
                symbol_type="class",
                sha256_hash=sha256_text(node_text(node)),
            ))
            body_node = node.child_by_field_name("body")
            if body_node:
                for m in body_node.children:
                    if m.type == "method_definition":
                        mname_node = m.child_by_field_name("name")
                        if mname_node:
                            mname = node_text(mname_node)
                            symbols.append(SymbolFingerprint(
                                file_path=file_path,
                                symbol_name=f"{cname}.{mname}",
                                symbol_type="method",
                                sha256_hash=sha256_text(node_text(m)),
                            ))
        elif ntype == "lexical_declaration":
            for decl in node.children:
                if decl.type == "variable_declarator":
                    vname_node = decl.child_by_field_name("name")
                    if vname_node:
                        vname = node_text(vname_node)
                        symbols.append(SymbolFingerprint(
                            file_path=file_path,
                            symbol_name=vname,
                            symbol_type="variable",
                            sha256_hash=sha256_text(node_text(decl)),
                        ))

    return symbols


def extract_py_symbols(file_path: str, code: str) -> List[SymbolFingerprint]:
    """Extract AST symbols and fingerprints from Python code using ast."""
    symbols: List[SymbolFingerprint] = []

    # Whole-file root fingerprint
    symbols.append(SymbolFingerprint(
        file_path=file_path,
        symbol_name="$file",
        symbol_type="file",
        sha256_hash=sha256_text(code),
    ))

    try:
        tree = ast.parse(code)
    except Exception:
        return symbols

    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            symbols.append(SymbolFingerprint(
                file_path=file_path,
                symbol_name=node.name,
                symbol_type="function",
                sha256_hash=sha256_text(ast.unparse(node)),
            ))
        elif isinstance(node, ast.ClassDef):
            symbols.append(SymbolFingerprint(
                file_path=file_path,
                symbol_name=node.name,
                symbol_type="class",
                sha256_hash=sha256_text(ast.unparse(node)),
            ))
            for item in node.body:
                if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    symbols.append(SymbolFingerprint(
                        file_path=file_path,
                        symbol_name=f"{node.name}.{item.name}",
                        symbol_type="method",
                        sha256_hash=sha256_text(ast.unparse(item)),
                    ))

    return symbols


def extract_file_symbols(file_path: str, code: str) -> List[SymbolFingerprint]:
    """Extract symbol fingerprints based on file extension."""
    ext = os.path.splitext(file_path)[1].lower()
    if ext in (".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs"):
        return extract_ts_js_symbols(file_path, code)
    elif ext == ".py":
        return extract_py_symbols(file_path, code)
    else:
        # File-level fingerprint for other formats (JSON, CSS, HTML, MD, etc.)
        return [SymbolFingerprint(
            file_path=file_path,
            symbol_name="$file",
            symbol_type="file",
            sha256_hash=sha256_text(code),
        )]


class VeylqoraGuard:
    """Evidence-anchored memory guard with per-session SQLite WAL tracking."""

    def __init__(self, db_path: str = "data/veylqora_memory.db") -> None:
        self.db_path = db_path
        os.makedirs(os.path.dirname(os.path.abspath(db_path)), exist_ok=True)
        self._init_db()

    def _get_connection(self) -> sqlite3.Connection:
        conn = sqlite3.connect(self.db_path, check_same_thread=False)
        conn.execute("PRAGMA journal_mode=WAL;")
        conn.execute("PRAGMA synchronous=NORMAL;")
        return conn

    def _init_db(self) -> None:
        conn = self._get_connection()
        try:
            with conn:
                conn.execute("""
                    CREATE TABLE IF NOT EXISTS session_metadata (
                        session_id TEXT PRIMARY KEY,
                        current_turn INTEGER NOT NULL DEFAULT 0,
                        created_at REAL NOT NULL,
                        updated_at REAL NOT NULL
                    );
                """)
                conn.execute("""
                    CREATE TABLE IF NOT EXISTS symbol_fingerprints (
                        session_id TEXT NOT NULL,
                        file_path TEXT NOT NULL,
                        symbol_name TEXT NOT NULL,
                        symbol_type TEXT NOT NULL,
                        sha256_hash TEXT NOT NULL,
                        first_seen_turn INTEGER NOT NULL,
                        last_seen_turn INTEGER NOT NULL,
                        PRIMARY KEY (session_id, file_path, symbol_name)
                    );
                """)
                conn.execute("""
                    CREATE TABLE IF NOT EXISTS cited_symbols (
                        session_id TEXT NOT NULL,
                        turn_index INTEGER NOT NULL,
                        file_path TEXT NOT NULL,
                        symbol_name TEXT NOT NULL,
                        PRIMARY KEY (session_id, turn_index, file_path, symbol_name)
                    );
                """)
        finally:
            conn.close()

    def get_journal_mode(self) -> str:
        """Verify the SQLite journal mode (should be 'wal')."""
        conn = self._get_connection()
        try:
            cur = conn.cursor()
            res = cur.execute("PRAGMA journal_mode;").fetchone()
            return str(res[0]).lower() if res else "unknown"
        finally:
            conn.close()

    def reset_session(self, session_id: str) -> None:
        """Clear all stored state for a given session."""
        conn = self._get_connection()
        try:
            with conn:
                conn.execute("DELETE FROM session_metadata WHERE session_id = ?", (session_id,))
                conn.execute("DELETE FROM symbol_fingerprints WHERE session_id = ?", (session_id,))
                conn.execute("DELETE FROM cited_symbols WHERE session_id = ?", (session_id,))
        finally:
            conn.close()

    def get_stored_fingerprints(self, session_id: str) -> Dict[Tuple[str, str], SymbolFingerprint]:
        """Fetch all stored fingerprints for a session."""
        conn = self._get_connection()
        try:
            cur = conn.cursor()
            rows = cur.execute(
                "SELECT file_path, symbol_name, symbol_type, sha256_hash FROM symbol_fingerprints WHERE session_id = ?",
                (session_id,)
            ).fetchall()
            return {
                (r[0], r[1]): SymbolFingerprint(file_path=r[0], symbol_name=r[1], symbol_type=r[2], sha256_hash=r[3])
                for r in rows
            }
        finally:
            conn.close()

    def inspect_turn(
        self,
        session_id: str,
        files: Dict[str, str],
        cited_symbols: Optional[List[str]] = None,
        advance_turn: bool = True,
    ) -> GuardReport:
        """Inspect current workspace files for a given session and detect mutations.

        Rules:
        - If Turn 0 (first time seeing session): records initial fingerprints, returns ACTIVE (0 stale).
        - If Turn > 0: compares new fingerprints against stored fingerprints.
          Only symbols/files that were cited or recorded in prior turns and whose fingerprint
          changed are reported as SUSPECTED_STALE.
        - Per-session isolation guarantees that session A changes never affect session B.
        """
        t0 = time.perf_counter()
        conn = self._get_connection()
        try:
            cur = conn.cursor()
            now = time.time()

            # Retrieve or initialize session metadata
            row = cur.execute(
                "SELECT current_turn FROM session_metadata WHERE session_id = ?",
                (session_id,)
            ).fetchone()

            if row is None:
                current_turn = 0
                with conn:
                    conn.execute(
                        "INSERT INTO session_metadata (session_id, current_turn, created_at, updated_at) VALUES (?, ?, ?, ?)",
                        (session_id, 0, now, now)
                    )
            else:
                current_turn = row[0]

            # Extract symbols from the current workspace snapshot
            current_symbols: Dict[Tuple[str, str], SymbolFingerprint] = {}
            for fpath, code in files.items():
                extracted = extract_file_symbols(fpath, code)
                for sym in extracted:
                    current_symbols[(sym.file_path, sym.symbol_name)] = sym

            # Fetch previously stored fingerprints for this session
            stored_fps = self.get_stored_fingerprints(session_id)

            mutated_symbols: List[MutatedSymbol] = []

            if current_turn > 0:
                # Turn > 0: Check for mutations against prior fingerprints
                for key, cur_sym in current_symbols.items():
                    if key in stored_fps:
                        old_sym = stored_fps[key]
                        if old_sym.sha256_hash != cur_sym.sha256_hash:
                            # A previously tracked symbol/file mutated!
                            mutated_symbols.append(MutatedSymbol(
                                file_path=cur_sym.file_path,
                                symbol_name=cur_sym.symbol_name,
                                symbol_type=cur_sym.symbol_type,
                                old_hash=old_sym.sha256_hash,
                                new_hash=cur_sym.sha256_hash,
                            ))

            # Record citations if provided
            new_turn = current_turn + 1 if advance_turn else current_turn
            with conn:
                # Update session metadata
                conn.execute(
                    "UPDATE session_metadata SET current_turn = ?, updated_at = ? WHERE session_id = ?",
                    (new_turn, now, session_id)
                )

                # Upsert current symbol fingerprints
                for (fpath, sname), sym in current_symbols.items():
                    conn.execute("""
                        INSERT INTO symbol_fingerprints (
                            session_id, file_path, symbol_name, symbol_type, sha256_hash, first_seen_turn, last_seen_turn
                        ) VALUES (?, ?, ?, ?, ?, ?, ?)
                        ON CONFLICT(session_id, file_path, symbol_name) DO UPDATE SET
                            sha256_hash = excluded.sha256_hash,
                            last_seen_turn = excluded.last_seen_turn
                    """, (session_id, fpath, sname, sym.symbol_type, sym.sha256_hash, new_turn, new_turn))

                # If specific symbols were cited in this turn, record them
                if cited_symbols:
                    for cs in cited_symbols:
                        # cs could be "src/App.tsx::Header" or "src/App.tsx"
                        if "::" in cs:
                            fp, sn = cs.split("::", 1)
                        else:
                            fp, sn = cs, "$file"
                        conn.execute("""
                            INSERT OR IGNORE INTO cited_symbols (session_id, turn_index, file_path, symbol_name)
                            VALUES (?, ?, ?, ?)
                        """, (session_id, new_turn, fp, sn))

            # Status determination
            stale_count = len(mutated_symbols)
            status = "SUSPECTED_STALE" if stale_count > 0 else "ACTIVE"
            elapsed_ms = round((time.perf_counter() - t0) * 1000, 2)

            return GuardReport(
                status=status,
                stale_count=stale_count,
                mutated_symbols=mutated_symbols,
                total_symbols_tracked=len(current_symbols),
                turn_index=new_turn,
                session_id=session_id,
                elapsed_ms=elapsed_ms,
            )
        finally:
            conn.close()

    def inspect_payload(
        self,
        payload: dict,
        session_id: Optional[str] = None
    ) -> GuardReport:
        """Inspect a chat completion payload by extracting <boltAction type="file" ...> files."""
        messages = payload.get("messages", [])

        # Derive stable session_id if none provided
        if not session_id:
            # Hash the system message or first user message to isolate by chat
            init_text = ""
            for m in messages:
                if m.get("role") in ("system", "user"):
                    c = m.get("content", "")
                    init_text += c if isinstance(c, str) else str(c)
                    if len(init_text) > 200:
                        break
            session_id = f"chat_{sha256_text(init_text)[:16]}" if init_text else "chat_default"

        # Extract file contents from all <boltAction type="file" filePath="..."> blocks
        action_pattern = re.compile(
            r'<boltAction\s+([^>]*?)>([\s\S]*?)<\/boltAction>',
            re.IGNORECASE
        )

        files: Dict[str, str] = {}
        for m in messages:
            content = m.get("content", "")
            if isinstance(content, str) and "<boltAction" in content:
                for match in action_pattern.finditer(content):
                    attrs = match.group(1)
                    body = match.group(2)
                    type_m = re.search(r'type=["\']([^"\']+)["\']', attrs)
                    path_m = re.search(r'filePath=["\']([^"\']+)["\']', attrs)
                    if type_m and type_m.group(1).lower() == "file" and path_m:
                        files[path_m.group(1).strip()] = body.strip()

        return self.inspect_turn(session_id=session_id, files=files)
